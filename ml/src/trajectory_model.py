"""
Lightweight regression model trained on synthetic trajectories generated by
trajectory_simulator.py.

BE HONEST ABOUT WHAT THIS PROVES: the training data comes from our own
deterministic simulator, so a high R² here proves the model learned to
approximate the simulator's formulas — it does NOT validate anything against
real-world CMR movement (no such data is available to this project). This
exists to demonstrate a genuine train/predict ML workflow and to give a
faster, generalizable approximation of the simulator, not as an independent
source of truth. The simulator remains the primary, explainable output.
"""

import random
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import r2_score, mean_absolute_error

from feature_engineering import BusinessCreditProfile
from trajectory_simulator import simulate_trajectory

FEATURE_NAMES = [
    "on_time_payment_pct", "has_recent_delinquency", "credit_utilization",
    "credit_tenure_years", "business_age_years",
    "industry_risk_low", "industry_risk_high",
    "effort_utilization", "effort_payment", "months_horizon",
]


def _random_profile(rng: random.Random) -> BusinessCreditProfile:
    return BusinessCreditProfile(
        on_time_payment_pct=rng.uniform(0.5, 1.0),
        has_recent_delinquency=rng.random() < 0.3,
        credit_utilization=rng.uniform(0.2, 0.95),
        credit_tenure_years=rng.uniform(0.5, 12),
        business_age_years=rng.uniform(0.5, 20),
        industry_risk_category=rng.choice(["low", "medium", "high"]),
    )


def generate_training_data(n_profiles: int = 300, seed: int = 42) -> list:
    rng = random.Random(seed)
    effort_options = [
        {"credit_utilization": False, "payment_history": False},
        {"credit_utilization": True, "payment_history": False},
        {"credit_utilization": False, "payment_history": True},
        {"credit_utilization": True, "payment_history": True},
    ]
    rows = []
    for _ in range(n_profiles):
        profile = _random_profile(rng)
        effort = rng.choice(effort_options)
        months_horizon = rng.randint(1, 18)
        trajectory = simulate_trajectory(profile, effort, months_horizon)
        result = trajectory[-1]

        rows.append({
            "on_time_payment_pct": profile.on_time_payment_pct,
            "has_recent_delinquency": int(profile.has_recent_delinquency),
            "credit_utilization": profile.credit_utilization,
            "credit_tenure_years": profile.credit_tenure_years,
            "business_age_years": profile.business_age_years,
            "industry_risk_low": int(profile.industry_risk_category == "low"),
            "industry_risk_high": int(profile.industry_risk_category == "high"),
            "effort_utilization": int(effort["credit_utilization"]),
            "effort_payment": int(effort["payment_history"]),
            "months_horizon": months_horizon,
            "resulting_score": result["overall_score"],
        })
    return rows


def train_trajectory_model(n_profiles: int = 3000, seed: int = 42):
    """Returns (fitted_model, metrics_dict). Fast — trains in well under a second."""
    rows = generate_training_data(n_profiles, seed)
    X = np.array([[r[f] for f in FEATURE_NAMES] for r in rows])
    y = np.array([r["resulting_score"] for r in rows])

    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=seed)
    model = RandomForestRegressor(n_estimators=200, random_state=seed)
    model.fit(X_train, y_train)

    preds = model.predict(X_test)
    metrics = {
        "r2": round(r2_score(y_test, preds), 4),
        "mae": round(mean_absolute_error(y_test, preds), 2),
        "n_train": len(X_train),
        "n_test": len(X_test),
    }
    return model, metrics


def predict_score_with_model(model, profile: BusinessCreditProfile, effort: dict, months_horizon: int) -> float:
    row = [
        profile.on_time_payment_pct,
        int(profile.has_recent_delinquency),
        profile.credit_utilization,
        profile.credit_tenure_years,
        profile.business_age_years,
        int(profile.industry_risk_category == "low"),
        int(profile.industry_risk_category == "high"),
        int(effort.get("credit_utilization", False)),
        int(effort.get("payment_history", False)),
        months_horizon,
    ]
    return round(float(model.predict([row])[0]), 1)
